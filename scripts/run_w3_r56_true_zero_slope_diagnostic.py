def independent_primitive_source(block,support):
    if (type(block) is not int or block not in range(BLOCKS)
            or support not in SUPPORT):
        raise ValueError("R56 unregistered new Gaussian primitive source")
    return fresh.fresh_source(
        block,support,n=PARTICIPANTS,master_seed=MASTER_SEED,
        n_blocks=BLOCKS,max_n=PARTICIPANTS,
    )


def paired_source_data(block,support):
    """Generate POSITIVE source and its EXACT same-innovation TRUE ZERO pair.

    Participant random slope is proportional to x_i(1+.25 t), using the
    original R16/R17 Gaussian positive source construction. Only that slope
    innovation is subtracted from the observed pointwise positive condition.
    All other source noise and native design/weights are held identically.
    """
    source=independent_primitive_source(block,support)
    X,y,w,g,time,trial,x,contrast,truth,raw_truth=r48.native_data(source)
    slope=source[0]["participant_slope"]
    if slope.shape[0]!=PARTICIPANTS or not np.issubdtype(np.asarray(g).dtype,np.integer):
        raise ValueError("R56 participant Gaussian innovation alignment failed")
    source_slope=np.asarray(slope,dtype=float)[np.asarray(g,int),0,0,0]
    contribution=(
        r16.SIGMA_RANDOM_SLOPE*source_slope*np.asarray(x,float)*
        (1.+.25*np.asarray(time,float))
    )
    if contribution.shape!=y.shape or not np.isfinite(contribution).all():
        raise ValueError("R56 invalid source slope innovation construction")
    shared={
        "X":X,"w":w,"group":g,"time":time,"trial":trial,
        "x":x,"contrast":contrast,"truth":float(truth),
        "raw_truth":float(raw_truth),
    }
    data={
        "true_positive":{**shared,"y":np.asarray(y,float).copy()},
        "true_zero":{**shared,"y":np.asarray(y,float)-contribution},
    }
    # No interpolation, reweighting, resimulation of trial errors,
    # perturbation of the fixed-effect truth or selection of participants.
    np.testing.assert_allclose(
        data["true_positive"]["y"]-data["true_zero"]["y"],
        contribution,rtol=2e-13,atol=2e-13,
    )
    return data,{
        "source_slope_contribution_norm":float(np.linalg.norm(contribution)),
        "mean_absolute_source_slope_contribution":float(np.mean(abs(contribution))),
        "native_rows":int(len(y)),
        "native_trials":int(len(source[1].time)),
        "fixed_projected_focal_truth":float(truth),
        "same_Gaussian_innovations_for_both_slope_states":True,
    }


