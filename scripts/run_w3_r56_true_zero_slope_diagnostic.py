def evaluate(block,support):
    pairs=[_empty_case(block,support,s) for s in SLOPE_STATES]
    try:
        inputs,design=paired_source_data(block,support)
    except Exception as exc:
        for row in pairs:
            row["original_source_error"]=repr(exc)[:500]
        return pairs
    for row in pairs:
        state=row["generating_slope_state"]
        data=inputs[state]
        row["original_source_status"]="ok"
        row["primitive_design"]=design
        fit=None
        try:
            fit=r49.fit_nuisance(data)
            row["nuisance_fit"]=_fit_ledger(fit)
        except Exception as exc:
            row["nuisance_fit"]={
                "status":"refused","reason":"original_Gaussian_REML_exception",
                "error":repr(exc)[:500],
                "numerical_starts":[{"label":name,"status":"not_attempted"}
                                    for name,_ in r49.START_RATIOS],
            }
        if fit is None or fit.get("status")!="accepted":
            row["conditional_fitted_CR2"]["reason"]="original_REML_numerical_refusal"
            continue
        ref=float(fit["reference_variance"])
        theta=float(fit["components"]["participant_slope"])
        ratio=theta/ref
        lower,upper=r54.active_signature(fit)
        row["source_parameter_ratio_lower_slope_active"]=bool(1 in lower)
        row["fitted_slope_variance_component"]=theta
        row["fitted_slope_ratio"]=float(ratio)
        row["fitted_slope_to_original_response_reference"]=ref
        try:
            cr2=r49.cr2_on(data,fit["working_blocks"])
            point=float(cr2["point"])
            se=float(cr2["cr2_se"])
            df=float(cr2["satterthwaite_df"])
            if not all(np.isfinite(z) and z>0 for z in (se,df)):
                raise ValueError("nonfinite CR2 variance or conditional df")
            crit=float(student_t.ppf(.95,df))
            if not np.isfinite(crit) or crit<=0:
                raise ValueError("invalid conditional reference critical")
            row["conditional_fitted_CR2"].update({
                "status":"ok","estimate":point,"se":se,
                "conditional_df":df,
                "nominal_90pct_conditional_critical":crit,
                "conditional_90pct_truth_included":bool(
                    abs(point-data["truth"])<=crit*se),
            })
        except Exception as exc:
            row["conditional_fitted_CR2"].update({
                "status":"refused","reason":repr(exc)[:500],
            })
    return pairs


def summarize(rows):
    universe={(b,s,state) for b in range(BLOCKS)
              for s in SUPPORT for state in SLOPE_STATES}
    keys=[(r["block"],r["support"],r["generating_slope_state"]) for r in rows]
    if len(keys)!=len(set(keys)) or not set(keys).issubset(universe):
        raise ValueError("R56 duplicate or unregistered generating source identity")
    for row in rows:
        if len(row["nuisance_fit"]["numerical_starts"])!=2:
            raise ValueError("R56 missing frozen original Gaussian numerical starts")
        if row["generating_slope_state"] not in SLOPE_STATES:
            raise ValueError("R56 source state not registered")
    paired={}
    strata={}
    for support in SUPPORT:
        for state in SLOPE_STATES:
            cases=[r for r in rows if r["support"]==support
                   and r["generating_slope_state"]==state]
            accepted=[r for r in cases if r["nuisance_fit"]["status"]=="accepted"]
            boundary=[r for r in accepted
                      if r["source_parameter_ratio_lower_slope_active"] is True]
            valid=[r for r in accepted
                   if r["conditional_fitted_CR2"]["status"]=="ok"]
            key=support+"/"+state
            strata[key]={
                "planned_new_primitive_blocks":BLOCKS,
                "recorded_paired_cases":len(cases),
                "source_generation_refusals":sum(
                    r["original_source_status"]!="ok" for r in cases),
                "accepted_observed_two_start_REML_fits":len(accepted),
                "original_REML_fit_refusals":len(cases)-len(accepted),
                "selected_positive_slope_ratio_lower_bound_count":len(boundary),
                "selected_positive_slope_ratio_lower_bound_denominator":
                    len(cases),
                "median_fitted_slope_variance":(
                    float(np.median([r["fitted_slope_variance_component"]
                                     for r in accepted])) if accepted else None),
                "median_fitted_slope_ratio":(
                    float(np.median([r["fitted_slope_ratio"]
                                     for r in accepted])) if accepted else None),
                "conditional_fitted_CR2_numerically_accepted":len(valid),
                "conditional_fitted_CR2_numerically_refused":
                    len(cases)-len(valid),
                "descriptive_conditional_90pct_focal_truth_inclusions":sum(
                    x["conditional_fitted_CR2"]["conditional_90pct_truth_included"]
                    for x in valid),
                "population_90pct_coverage_qualified":False,
            }
        matches=[]
        for b in range(BLOCKS):
            x={r["generating_slope_state"]:r for r in rows
               if r["block"]==b and r["support"]==support}
            if set(x)!=set(SLOPE_STATES):
                continue
            a=x["true_zero"];v=x["true_positive"]
            if (a["nuisance_fit"]["status"]=="accepted" and
                v["nuisance_fit"]["status"]=="accepted"):
                matches.append(
                    v["fitted_slope_variance_component"]-
                    a["fitted_slope_variance_component"])
        paired[support]={
            "planned_independent_primitive_blocks":BLOCKS,
            "complete_observed_two_state_pairs":len(matches),
            "median_positive_minus_zero_fitted_slope_variance":(
                float(np.median(matches)) if matches else None),
            "positive_minus_zero_slopes_are_paired_not_independent":True,
        }
    return {
        "study":STUDY,"new_source_seed":MASTER_SEED,
        "new_independent_Gaussian_primitive_blocks":BLOCKS,
        "paired_leverage_support_not_independent_sources":True,
        "true_zero_and_positive_states_paired_on_same_innovations":True,
        "native_participants_per_source":PARTICIPANTS,
        "planned_primitive_leverage_pairs":N_PAIRED_DESIGNS,
        "planned_source_slope_state_cases":N_CASES,
        "recorded_source_slope_state_cases":len(rows),
        "planned_original_Gaussian_REML_fit_slots":N_CASES,
        "planned_original_two_start_optimizer_outcome_slots":N_OPTIMIZER_STARTS,
        "recorded_original_two_start_optimizer_outcome_slots":
            sum(len(r["nuisance_fit"]["numerical_starts"]) for r in rows),
        "complete_failure_inclusive_original_source_denominator":
            len(rows)==N_CASES,
        "true_zero_source_variance_is_structural_not_optimizer_bound":True,
        "estimator_preserves_original_strict_positive_slope_ratio_box":True,
        "no_true_zero_boundary_null_typeI_power_calibration":True,
        "no_nuisance_estimation_aware_CR2_pointwise_inference":True,
        "no_90pct_simultaneous_function_bands":True,
        "no_MNAR_or_whole_participant_selection_identification":True,
        "release_authorized":False,
        "strata":strata,
        "paired_slope_differences":paired,
    }


def _write(path,obj):
    path.write_text(json.dumps(
        r53._json_plain(obj),sort_keys=True,indent=2,allow_nan=False)+"\n")


def shard(out,start,stop):
    if (start,stop) not in SHARDS:
        raise ValueError("R56 source shard outside frozen independent blocks")
    out.mkdir(parents=True,exist_ok=True)
    records=[r for b in range(start,stop) for s in SUPPORT
             for r in evaluate(b,s)]
    _write(out/"cases.json",records)
    _write(out/"manifest.json",{
        "study":STUDY,"block_start":start,"block_stop":stop,
        "new_source_seed":MASTER_SEED,
        "original_GitHub_merge_checkout":os.environ.get(
            "GITHUB_SHA","unverified-local"),
        "cases_sha256":hashlib.sha256((out/"cases.json").read_bytes()).hexdigest(),
        "records":len(records),
    })


def aggregate(out,parts):
    manifests=list(parts.glob("*/manifest.json"))
    if len(manifests)!=len(SHARDS):
        raise ValueError("R56 missing one or more original science shards")
    identity=os.environ.get("GITHUB_SHA","unverified-local")
    found=set()
    cases=[]
    for path in manifests:
        item=json.loads(path.read_text())
        part=(item["block_start"],item["block_stop"])
        if (part not in SHARDS or part in found or
            item["study"]!=STUDY or item["new_source_seed"]!=MASTER_SEED or
            item["original_GitHub_merge_checkout"]!=identity):
            raise ValueError("R56 source manifest/replay identity mismatch")
        found.add(part)
        raw=(path.parent/"cases.json").read_bytes()
        if hashlib.sha256(raw).hexdigest()!=item["cases_sha256"]:
            raise ValueError("R56 original case shard SHA256 corrupted")
        subset=json.loads(raw)
        expected={(b,s,z) for b in range(*part) for s in SUPPORT
                  for z in SLOPE_STATES}
        if (len(subset)!=item["records"] or
            {(r["block"],r["support"],r["generating_slope_state"])
              for r in subset}!=expected):
            raise ValueError("R56 nonmatching original independent Gaussian source IDs")
        cases.extend(subset)
    if found!=set(SHARDS):
        raise ValueError("R56 source primitive shards incomplete")
    cases.sort(key=lambda r:(r["block"],SUPPORT.index(r["support"]),
                             SLOPE_STATES.index(r["generating_slope_state"])))
    result=summarize(cases)
    if not result["complete_failure_inclusive_original_source_denominator"]:
        raise ValueError("R56 source denominator missing")
    out.mkdir(parents=True,exist_ok=True)
    _write(out/"cases.json",cases)
    _write(out/"summary.json",result)
    (out/"source-commit.txt").write_text(identity+"\n")
    files=("cases.json","summary.json","source-commit.txt")
    (out/"SHA256SUMS").write_text("".join(
        hashlib.sha256((out/f).read_bytes()).hexdigest()+"  "+f+"\n"
        for f in files))
    print("R56 TRUE ZERO versus POSITIVE Gaussian source:",json.dumps(
        result,sort_keys=True))


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--out",type=Path,required=True)
    group=p.add_mutually_exclusive_group(required=True)
    group.add_argument("--start",type=int)
    group.add_argument("--merge-parts",type=Path)
    p.add_argument("--stop",type=int)
    a=p.parse_args()
    if a.merge_parts is not None:
        aggregate(a.out,a.merge_parts)
    elif a.stop is not None:
        shard(a.out,a.start,a.stop)
    else:
        raise SystemExit("R56 requires registered source shard endpoints")


if __name__=="__main__":
    main()
