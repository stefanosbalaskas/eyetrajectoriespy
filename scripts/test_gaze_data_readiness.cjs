"use strict";
const assert=require("node:assert/strict");
const tool=require("../docs/javascripts/gaze-data-readiness.js");
const header="participant_id,trial_id,time_s,x,y,condition";
function run(rows,opts){return tool.inspect(tool.parseCsv([header,...rows].join("\n")+"\n"),opts);}
const dense=run(["A,T1,0,0.1,0.2,c","A,T1,1,0.2,0.3,c","B,T1,0,0.3,0.4,c","B,T1,1,0.4,0.5,c"],{coordinateSystem:"normalized",timeUnit:"seconds"});
assert.equal(dense.commonGrid,true);
assert.equal(dense.curves,2);
assert.equal(dense.participants,2);
assert.equal(dense.missingCoordinateRows,0);
const repeated=run(["A,T1,0,0.1,0.2,c","A,T2,0,0.3,0.4,c"]);
assert.equal(repeated.repeatedTrials,true);
const sparse=run(["A,T1,0,0.1,0.2,c","A,T1,1,0.2,0.3,c","B,T1,0,0.3,0.4,c","B,T1,0.8,0.4,0.5,c"]);
assert.equal(sparse.commonGrid,false);
assert.match(sparse.suggestedReading,/Paired native/);
const async=run(["A,T1,0,0.1,,c","A,T1,0.2,,0.3,c"]);
assert.equal(async.coordinateSpecificRows,2);
const bad=run(["A,T1,0,1.4,0.2,c","A,T1,0,0.3,,c","A,T1,-1,abc,0.2,c"],{coordinateSystem:"normalized",timeUnit:"seconds"});
assert.equal(bad.duplicateWithinTrialTimes,1);
assert.equal(bad.nonincreasingTimes,2);
assert.equal(bad.invalidCoordinateRows,1);
assert.equal(bad.outsideDeclaredNormalizedRows,1);
const parsed=tool.parseCsv("\uFEFF"+header+"\r\n\"A, one\",\"Trial \"\"A\"\"\",0,0.1,0.2,c\r\n");
assert.equal(parsed.rows[0][0],"A, one");
assert.equal(parsed.rows[0][1],'Trial "A"');
assert.throws(()=>tool.parseCsv(header+"\nA,T1,0,0.1\n"),/cells; expected/);
assert.throws(()=>tool.parseCsv(header+"\n\"A,T1,0,0.1,0.2\n"),/Unterminated/);
assert.throws(()=>tool.inspect(tool.parseCsv("time_s,x,y\n0,0.1,0.2\n")),/Required columns/);
assert.throws(()=>tool.parseCsv(header+"\n"+"A,T1,0,0.1,0.2,c\n".repeat(12001)),/12,000/);
console.log("PASS browser CSV parser, structural diagnostics and misuse limits");
