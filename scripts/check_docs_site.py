"""Narrow regression audit for the site's hand-authored interactive surfaces.

Not a WCAG certification or an external crawling/link-availability guarantee.
Uses only the Python stdlib; generated SVG gallery references are built in docs CI.
"""
from __future__ import annotations

import re
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
PAGES = (
    "tools/method-selector.md",
    "tools/trajectory-explorer.md",
    "tools/figure-explorer.md",
    "tools/evidence-explorer.md",
    "tools/workflow-comparison.md",
    "tutorials/reproducible-starter.md",
    "versions/index.md",
)
ASSETS = (
    "javascripts/interactive-explorers.js",
    "assets/interactive-explorers.css",
    "downloads/synthetic-gaze-common-grid.csv",
    "downloads/run_synthetic_gaze.py",
)
HREF = re.compile(r'(?:href|src)=["\x27]([^"\x27]+)["\x27]|(?<!!)\[[^\]]+\]\(([^)]+)\)')
IMG = re.compile(r"<img\b[^>]*>", flags=re.I)
LABEL = re.compile(r'<label\b[^>]*\bfor="([^"]+)"')
ID = re.compile(r'\bid="([^"]+)"')


def target_exists(page: Path, dest: str) -> bool:
    path = urlsplit(dest).path
    if not path or dest.startswith(("#", "mailto:")) or urlsplit(dest).scheme:
        return True
    file = (page.parent / unquote(path)).resolve()
    if not file.is_relative_to(DOCS.resolve()):
        return False
    if file.is_file():
        return True
    if file.is_dir() and (file / "index.md").is_file():
        return True
    if path.endswith("/") and file.with_suffix(".md").is_file():
        return True
    if path.endswith("/") and (file / "index.md").is_file():
        return True
    if not Path(path).suffix and file.with_suffix(".md").is_file():
        return True
    # The illustrated gallery is generated by scripts/generate_docs_gallery.py
    # inside the existing docs CI pipeline, before the strict MkDocs build.
    if "/assets/gallery/" in file.as_posix() and path.endswith(".svg"):
        return True
    return False


def main() -> None:
    for rel in (*PAGES, *ASSETS):
        assert (DOCS / rel).is_file(), "Missing documentation file: " + rel
    for rel in PAGES:
        page = DOCS / rel
        content = page.read_text(encoding="utf-8")
        assert content.startswith("---\n"), "Missing MkDocs metadata: " + rel
        missing = [
            dest for m in HREF.finditer(content)
            if not target_exists(page, m.group(1) or m.group(2))
            for dest in [m.group(1) or m.group(2)]
        ]
        assert not missing, "Invalid internal links: " + rel + ": " + str(missing)
        ids = set(ID.findall(content))
        for id_ in LABEL.findall(content):
            assert id_ in ids, "Label without control: " + rel + ": " + id_
        for img in IMG.findall(content):
            assert re.search(r'\balt="[^"]+"', img), "Missing image alt: " + rel
        if "data-et-collection" in content:
            assert 'data-et-count aria-live="polite"' in content
            assert "data-et-entry" in content
        if rel == "tools/workflow-comparison.md":
            assert content.count("<tr data-et-entry ") == 10
    script = (DOCS / "javascripts/interactive-explorers.js").read_text(encoding="utf-8")
    for required in ("document$.subscribe(init)", "initMethod()", "initTrajectory()", "initFilters()", "aria-label"):
        assert required in script, "Missing interaction contract: " + required
    import csv
    with (DOCS / "downloads/synthetic-gaze-common-grid.csv").open(newline="", encoding="utf-8") as file:
        rows = list(csv.DictReader(file))
    assert len(rows) == 12 * 41, "Synthetic fixture row count changed"
    assert len({r["participant_id"] for r in rows}) == 12
    assert all(0 <= float(r["x"]) <= 1 and 0 <= float(r["y"]) <= 1 for r in rows)
    compile((DOCS / "downloads/run_synthetic_gaze.py").read_text(encoding="utf-8"), "run_synthetic_gaze.py", "exec")
    print("PASS: interactive documentation links, controls, fixture and source contracts")


if __name__ == "__main__":
    main()
