"""Exploratory R16 CR2 working-identity factorial pilot; never a calibration gate.

24 fresh source blocks beyond the original R16 range are generated by the same
independent source family (seed + offset block). This pilot reuses the original
R16 blocks 0:24 instead to preserve direct paired truth/CR1 comparisons; it is
NOT an independent confirmatory replication of R16.
"""
from __future__ import annotations
import argparse
from hashlib import sha256
import json
import os
from pathlib import Path
import numpy as np
from scipy.stats import t as student_t
from scripts.run_w3_r16_leverage_covariance_factorial import (
    source,fit,basis,TIME,FOCAL,MODELS,SUPPORT,SEED,truth_coefficients
)
from scripts.w3_r16_cr2_reference import cr2_wls_identity

BLOCKS=24
SIZES=(24,)
NOMINAL=.90
STUDY="W3_R16_CR2_IDENTITY_FACTORIAL_EXPLORATORY_PILOT"
def one(block,n,support,model):
    record=dict(block=block,n_participants=n,support=support,model=model,
                status="failed",exception=None,production_release_ready=False,
                calibrated_inference_qualified=False)
    try:
        data=source(block,n,support)
        raw,gaze,x,person,trial,means=data
        counts=np.bincount(person,minlength=n)
        XX=[];YY=[];WW=[]
        k=basis(np.array([TIME[FOCAL]]),model).shape[1]
        c=np.r_[np.zeros(k),basis(np.array([TIME[FOCAL]]),model)[0]]
        for t,y,xi,who in zip(gaze.time,gaze.values,x,person):
            B=basis(t,model)
            XX.append(np.column_stack([B,xi*B]))
            YY.append(y[:,0])
            WW.append(np.full(len(t),1/(counts[who]*len(t))))
        X=np.vstack(XX)
        y=np.concatenate(YY)
        w=np.concatenate(WW)
        unit=np.concatenate([np.full(len(t),who) for t,who in zip(gaze.time,person)])
        independent=cr2_wls_identity(X,y,w,unit,c)
        previous=fit(data,model)
        if abs(independent["point"]-previous["point"])>4e-7:
            raise ValueError("CR2 regression coefficient differs from R16 weighted QR")
        if independent["numerical_difference"]>2e-7:
            raise ValueError("independent CR2 dense reference numerical mismatch")
        critical=float(student_t.ppf(.95,n-1))
        truth=float(truth_coefficients(TIME)[1,FOCAL,0])
        se=independent["cr2_se"]
        record.update(status="ok",cr2_se=se,cr1_se=previous["cr1_se"],
                      cv3j_se=previous["jack_se"],oracle_se=previous["oracle_se"],
                      cr2_oracle_se_ratio=se/previous["oracle_se"],
                      cr2_t_n_minus_1_truth_included=bool(abs(previous["point"]-truth)<=critical*se),
                      cr1_t_n_minus_1_truth_included=bool(abs(previous["point"]-truth)<=critical*previous["cr1_se"]),
                      cv3j_t_n_minus_1_truth_included=bool(abs(previous["point"]-truth)<=critical*previous["jack_se"]),
                      oracle_t_n_minus_1_truth_included=bool(abs(previous["point"]-truth)<=critical*previous["oracle_se"]),
                      dense_oracle_delta=independent["numerical_difference"],
                      focal_contrast_effective_clusters=previous["contrast_effective_clusters"],
                      cr2_target="working_identity_in_whitened_space",
                      df_qualified=False)
    except Exception as exc:
        record["exception"]=dict(type=type(exc).__name__,message=str(exc)[:500])
    return record

def summarize(rows):
    groups={}
    for s in SUPPORT:
        for m in MODELS:
            r=[v for v in rows if v["support"]==s and v["model"]==m and v["status"]=="ok"]
            groups[f"{s}/{m}"]=dict(completed=len(r),planned=BLOCKS,
                counts={name:sum(x[name] for x in r) for name in (
                    "cr1_t_n_minus_1_truth_included",
                    "cv3j_t_n_minus_1_truth_included",
                    "cr2_t_n_minus_1_truth_included",
                    "oracle_t_n_minus_1_truth_included")},
                mean_cr2_to_oracle_se_ratio=float(np.mean([x["cr2_oracle_se_ratio"] for x in r])) if r else None)
    return dict(study=STUDY,source_master_seed=SEED,
                independent_generating_blocks=BLOCKS,
                planned_cases=BLOCKS*len(SIZES)*len(SUPPORT)*len(MODELS),
                recorded_cases=len(rows),successful_cases=sum(r["status"]=="ok" for r in rows),
                failed_cases=sum(r["status"]!="ok" for r in rows),
                groups=groups,exploratory=True,
                cr2_working_target_correct_for_true_covariance=False,
                cr2_df_qualified=False,production_release_ready=False)

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--out",type=Path,required=True)
    args=p.parse_args()
    args.out.mkdir(parents=True,exist_ok=True)
    rows=[one(b,24,s,m) for b in range(BLOCKS) for s in SUPPORT for m in MODELS]
    report=summarize(rows)
    for name,obj in (("case-ledger.json",rows),("summary.json",report)):
        (args.out/name).write_text(json.dumps(obj,indent=2,sort_keys=True)+"\n")
    (args.out/"source-commit.txt").write_text(os.getenv("GITHUB_SHA","unverified-local")+"\n")
    files=["case-ledger.json","summary.json","source-commit.txt"]
    (args.out/"SHA256SUMS").write_text("".join(
        sha256((args.out/name).read_bytes()).hexdigest()+"  "+name+"\n" for name in files))
    print("R16 CR2 PILOT:",json.dumps(report,sort_keys=True))
    if report["failed_cases"] or report["successful_cases"]!=report["planned_cases"]:
        raise SystemExit("CR2 numerical/scientific failures retained")

if __name__=="__main__":
    main()
